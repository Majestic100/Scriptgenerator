export const translations: Record<Lang, typeof da> = { da, en };

/** Viser en gemt varighed ('30-40 sekunder') på det aktive sprog uden at ændre værdien. */
export const formatDuration = (duration: string | undefined, lang: Lang): string => {
  if (!duration) return '';
  return lang === 'en' ? duration.replace('sekunder', 'seconds') : duration;
};

/** Datolokale til toLocaleDateString. */
export const dateLocale = (lang: Lang) => (lang === 'en' ? 'en-GB' : 'da-DK');

const STORAGE_KEY = 'script_generator_lang';

interface LanguageContextValue {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: typeof da;
}

const LanguageContext = createContext<LanguageContextValue>({
  lang: 'da',
  setLang: () => {},
  t: da
});

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [lang, setLangState] = useState<Lang>(() => {
    try {
      const stored = localStorage.getItem(STORAGE_KEY);
      return stored === 'en' ? 'en' : 'da';
    } catch {
      return 'da';
    }
  });

  const setLang = (next: Lang) => {
    setLangState(next);
    try {
      localStorage.setItem(STORAGE_KEY, next);
    } catch {}
  };

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  return (
    <LanguageContext.Provider value={{ lang, setLang, t: translations[lang] }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLang = () => useContext(LanguageContext);
